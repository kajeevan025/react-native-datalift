import CoreML

final class LayoutLMv3OnnxEngine {
    private let minimumTokenConfidence = 0.88

    struct Prediction {
        let used: Bool
        let runtime: String
        let confidence: Double
        let fields: [String: Any]
        let warnings: [String]
    }

    private var model: MLModel?
    private var loadedModelPath: String?

    func predict(
        modelPath: String,
        labelsPath: String?,
        text: String,
        image: UIImage?
    ) throws -> Prediction {
        // Load labels — nil/missing path falls back to built-in defaults automatically
        let rawLabels = loadLabels(labelsPath: labelsPath)
        // Validate; if incompatible (e.g. downloaded file uses different vocab)
        // fall back to the built-in invoice defaults so extraction still runs.
        let labels: [Int: String]
        if isValidLabelMap(rawLabels) {
            labels = rawLabels
        } else {
            labels = defaultLabels()
        }
        let bpeVocab = loadVocab(modelPath: modelPath)
        let encoded = encode(text: text, bpeVocab: bpeVocab, maxSeqLen: 512)
        let mlModel = try getModel(modelPath: modelPath)
        let featureProvider = try buildFeatureProvider(
            model: mlModel,
            encoded: encoded,
            image: image,
            imageSide: 224
        )
        let output = try mlModel.prediction(from: featureProvider)
        let logits = try readLogits(from: output)
        let entities = decodeEntities(logits: logits, tokens: encoded.tokens, labels: labels)
        let fields = entitiesToFields(entities)
        let confidence = entities.map(\ .score).max() ?? 0
        var warnings: [String] = []
        if entities.isEmpty {
            warnings.append("No high-confidence entities survived post-processing")
        }
        if fields.isEmpty {
            warnings.append("No validated schema fields could be derived from model predictions")
        }

        return Prediction(
            used: !fields.isEmpty,
            runtime: "coreml-ios",
            confidence: confidence,
            fields: fields,
            warnings: warnings
        )
    }

